// Conta mensal marcada como "Mensal" depois que o mês seguinte já veio no extrato (com outro nome):
// o app não cria a cópia "gerado automaticamente"; e uma cópia que já exista aparece em "Para revisar"
// para juntar, apagando sempre a gerada. Números e nomes inventados.
import { test, before, after } from "node:test";
import assert from "node:assert/strict";
import { iniciarServidor, abrirNavegador, abrirPainel } from "./ambiente.mjs";

let servidor, browser;
before(async () => { servidor = await iniciarServidor(); browser = await abrirNavegador(); });
after(async () => { await browser?.close(); servidor?.srv.close(); });

const hoje = new Intl.DateTimeFormat("en-CA", { timeZone: "America/Boa_Vista" }).format(new Date());
const [ano, mes] = hoje.slice(0, 7).split("-").map(Number);
const ym = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}`;
const atual = ym(new Date(ano, mes - 1, 1)), anterior = ym(new Date(ano, mes - 2, 1));
const base = { banco: "Banco do Brasil", modalidade: "Pix", classificacao: "Fixa", escopo: "meu", tipo: "despesa" };


test("conta mensal já paga no extrato com outro nome não ganha cópia gerada", async () => {
  const { ctx, page, erros } = await abrirPainel(browser, servidor.base);
  try {
    const lista = [
      { ...base, id: "ipva-ant", valor: 293.89, dataLanc: `${anterior}-05`, dataEfet: `${anterior}-05`, descricao: "IPVA CARRO", categoria: "Transporte", recorrencia: "Mensal" },
      { ...base, id: "ipva-ext", banco: "banco do brasil", valor: 293.89, dataLanc: `${atual}-05`, dataEfet: `${atual}-05`, descricao: "GOVERNO FICTICIO - IPVA", categoria: "A categorizar", recorrencia: "Única" },
      { ...base, id: "net-ant", valor: 99.9, dataLanc: `${anterior}-10`, dataEfet: `${anterior}-10`, descricao: "INTERNET FICTICIA", categoria: "Contas", recorrencia: "Mensal" },
    ];
    const depois = await page.evaluate((l) => { const t = window.__genesisTeste; t.definirLancamentos(l); t.gerarRecorrentes(); return t.lancamentos(); }, lista);
    const doMes = (d) => depois.filter((t) => t.dataEfet.startsWith(atual) && t.descricao === d);
    assert.equal(doMes("IPVA CARRO").length, 0, "o IPVA deste mês já veio no extrato");
    assert.equal(doMes("INTERNET FICTICIA").length, 1, "a internet deste mês ainda não veio: continua sendo gerada");
    assert.deepEqual(erros, []);
  } finally { await ctx.close(); }
});

test("cópia gerada que já existe ao lado da conta do extrato vai para Para revisar e Juntar apaga a gerada", async () => {
  const { ctx, page, erros } = await abrirPainel(browser, servidor.base);
  try {
    await page.evaluate(() => { window.confirm = () => true; });
    await page.evaluate((l) => window.__genesisTeste.definirLancamentos(l), [
      { ...base, id: "fac-ger", valor: 769.1, dataLanc: `${atual}-05`, dataEfet: `${atual}-05`, descricao: "MENSALIDADE FICTICIA", categoria: "Faculdade", recorrencia: "Mensal", seriesId: "fac", autoGenerated: true },
      { ...base, id: "fac-ext", modalidade: "Débito", valor: 769.1, dataLanc: `${atual}-05`, dataEfet: `${atual}-05`, descricao: "FACULDADE FICTICIA · Pagamento", categoria: "A categorizar", recorrencia: "Única" },
      { ...base, id: "outra", valor: 50, dataLanc: `${atual}-05`, dataEfet: `${atual}-05`, descricao: "OUTRA COISA", categoria: "Contas", recorrencia: "Mensal", seriesId: "x", autoGenerated: true },
    ]);
    await page.evaluate(() => { location.hash = "#inicio"; });
    const banner = page.locator("#dupBanner");
    assert.match(await banner.innerText(), /MENSALIDADE FICTICIA[\s\S]*FACULDADE FICTICIA/);
    assert.equal(await banner.locator(".review-row").count(), 1);
    await banner.locator(".dup-del").click();
    await page.waitForFunction(() => !window.__genesisTeste.lancamentos().some((t) => t.id === "fac-ger"));
    const ids = (await page.evaluate(() => window.__genesisTeste.lancamentos())).map((t) => t.id).sort();
    assert.deepEqual(ids, ["fac-ext", "outra"]);
    assert.deepEqual(erros, []);
  } finally { await ctx.close(); }
});
