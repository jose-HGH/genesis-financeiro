// Pergunta automática: a mesma categoria como entrada e saída de mesmo valor no mês. Números inventados.
import { test, before, after } from "node:test";
import assert from "node:assert/strict";
import { iniciarServidor, abrirNavegador, abrirPainel } from "./ambiente.mjs";

let servidor, browser;
before(async () => { servidor = await iniciarServidor(); browser = await abrirNavegador(); });
after(async () => { await browser?.close(); servidor?.srv.close(); });

const hoje = new Intl.DateTimeFormat("en-CA", { timeZone: "America/Boa_Vista" }).format(new Date());
const mudar = (ym, n) => { let [y, m] = ym.split("-").map(Number); m += n; while (m < 1) { m += 12; y--; } while (m > 12) { m -= 12; y++; } return `${y}-${String(m).padStart(2, "0")}`; };
const mes = mudar(hoje.slice(0, 7), -1), prox = hoje.slice(0, 7), prox2 = mudar(prox, 1);
const base = { banco: "Banco Ficticio", modalidade: "Pix", classificacao: "Fixa", escopo: "meu", recorrencia: "Única" };
const L = (id, tipo, valor, d, desc, categoria, x = {}) => ({ ...base, id, tipo, valor, dataLanc: d, dataEfet: d, descricao: desc, categoria, ...x });
const dados = () => [
  L("rec", "receita", 3000, `${mes}-06`, "PIX RECEBIDO FICTICIO", "Aluguel"),
  L("desp", "despesa", 3000, `${mes}-10`, "CASA ALUGADA FICTICIA", "Aluguel", { recorrencia: "Mensal", seriesId: "s1" }),
  L("desp2", "despesa", 3000, `${prox}-10`, "CASA ALUGADA FICTICIA", "Aluguel", { recorrencia: "Mensal", seriesId: "s1", autoGenerated: true }),
  L("desp3", "despesa", 3000, `${prox2}-10`, "CASA ALUGADA FICTICIA", "Aluguel", { recorrencia: "Mensal", seriesId: "s1", autoGenerated: true }),
  L("sal", "receita", 3200, `${mes}-20`, "SALARIO FICTICIO", "Salário"),
  L("cons", "despesa", 1500, `${mes}-06`, "CONSORCIO FICTICIO", "Outros"),
  L("x1", "receita", 100, `${mes}-03`, "VENDA FICTICIA", "Outros"), // valores diferentes: não pergunta
];

async function abrir() {
  const p = await abrirPainel(browser, servidor.base);
  await p.page.evaluate((l) => window.__genesisTeste.definirLancamentos(l), dados());
  const box = p.page.locator("#ajustesBox");
  await box.waitFor();
  return { ...p, box };
}

test("ajustes: pergunta com opções e efeito; 'eu recebo' apaga a saída e vira a série", async () => {
  const { ctx, page, erros, box } = await abrir();
  try {
    assert.match(await box.innerText(), /Aluguel aparece como entrada e como saída de R\$\s?3\.000,00/);
    await box.locator('[data-aj="ver"]').click();
    const txt = await box.innerText();
    assert.match(txt, /Hoje o resultado de .* é R\$\s?1\.800,00/); // 3000 + 3200 + 100 − 3000 − 1500
    assert.match(txt, /apaga a saída e os próximos 2 lançamentos da série mudam junto; resultado de .*: R\$\s?4\.800,00/);
    assert.match(txt, /apaga a entrada; resultado de .*: -R\$\s?1\.200,00/);
    await box.locator('[data-aj="op"]').first().click();
    const l = await page.evaluate(() => window.__genesisTeste.lancamentos());
    const por = Object.fromEntries(l.map((t) => [t.id, t]));
    assert.equal(por.desp, undefined, "a saída sai dos lançamentos (vai para Apagados recentemente)");
    assert.equal(por.desp2.tipo, "receita");
    assert.equal(por.desp3.tipo, "receita");
    assert.equal(por.rec.tipo, "receita");
    assert.ok(await box.isHidden(), "depois de responder, a pergunta some");
    assert.deepEqual(erros, []);
  } finally { await ctx.close(); }
});

test("ajustes: 'deixar como está' não muda nada e não pergunta de novo; 'responder depois' esconde", async () => {
  const { ctx, page, erros, box } = await abrir();
  try {
    await box.locator('[data-aj="depois"]').click();
    assert.ok(await box.isHidden());
    await page.evaluate((l) => window.__genesisTeste.definirLancamentos(l), dados());
    assert.ok(await box.isHidden(), "adiado por 3 dias");
    assert.deepEqual(erros, []);
  } finally { await ctx.close(); }
  const p2 = await abrir();
  try {
    await p2.box.locator('[data-aj="ver"]').click();
    await p2.box.locator('[data-aj="op"]').nth(3).click();
    const l = await p2.page.evaluate(() => window.__genesisTeste.lancamentos());
    assert.equal(l.length, 7, "nada foi apagado");
    assert.equal(l.find((t) => t.id === "desp").tipo, "despesa");
    assert.ok(await p2.box.isHidden());
    await p2.page.evaluate((l) => window.__genesisTeste.definirLancamentos(l), dados());
    assert.ok(await p2.box.isHidden(), "resposta guardada: não pergunta de novo");
    assert.deepEqual(p2.erros, []);
  } finally { await p2.ctx.close(); }
});
